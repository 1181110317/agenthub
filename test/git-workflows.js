const assert = require('assert');
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'ah-git-workflows-'));
process.env.AGENTHUB_DATA_DIR = path.join(tmp, 'data');
const git = require('../lib/git');
const workflows = require('../lib/git-workflows');
const run = (cwd, args) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], windowsHide: true }).trim();
const work = path.join(tmp, 'work'), remote = path.join(tmp, 'remote.git'), peer = path.join(tmp, 'peer');
const config = cwd => { run(cwd, ['config', 'user.name', 'AgentHub QA']); run(cwd, ['config', 'user.email', 'qa@example.test']); run(cwd, ['config', 'core.autocrlf', 'false']); };
(async () => {
  try {
    fs.mkdirSync(work); run(tmp, ['init', '--bare', remote]); run(work, ['init', '-b', 'main']); config(work);
    fs.writeFileSync(path.join(work, '文件.txt'), 'one\n'); run(work, ['add', '-A']); run(work, ['commit', '-m', 'initial']);
    run(work, ['remote', 'add', 'origin', remote]); run(work, ['push', '-u', 'origin', 'main']);
    let state = await workflows.snapshot(work); const original = state.head;
    assert(state.branches.some(b => b.current && b.name === 'main'));
    fs.writeFileSync(path.join(work, '文件.txt'), 'two\n'); fs.writeFileSync(path.join(work, 'new.txt'), 'untracked\n');
    await assert.rejects(() => workflows.mutate(work, { action: 'branch-create', name: 'work/feature', expectedHead: original }), /工作区/);
    await workflows.mutate(work, { action: 'stash-save', message: '中文 stash $(not-a-command)', expectedHead: original });
    state = await workflows.snapshot(work); assert.equal(state.stashes.length, 1); assert.equal(state.status.files.length, 0);
    await workflows.mutate(work, { action: 'branch-create', name: 'work/feature', expectedHead: original });
    await workflows.mutate(work, { action: 'stash-apply', oid: state.stashes[0].oid, expectedHead: original });
    assert.equal(fs.readFileSync(path.join(work, '文件.txt'), 'utf8'), 'two\n'); assert(fs.existsSync(path.join(work, 'new.txt')));
    assert.equal((await workflows.snapshot(work)).stashes.length, 1, 'apply keeps stash until explicit deletion');
    await assert.rejects(() => workflows.mutate(work, { action: 'pull', expectedHead: original }), /工作区/);
    run(work, ['add', '-A']); run(work, ['commit', '-m', 'feature']);
    await assert.rejects(() => workflows.mutate(work, { action: 'branch-switch', name: 'main', expectedHead: original }), /HEAD/);
    await workflows.mutate(work, { action: 'branch-switch', name: 'main', expectedHead: await workflows.head(work) });
    await assert.rejects(() => workflows.mutate(work, { action: 'branch-create', name: '--force', expectedHead: original }), /分支名/);
    await assert.rejects(() => workflows.mutate(work, { action: 'branch-create', name: '@{-1}', expectedHead: original }), /分支名/);
    await assert.rejects(() => workflows.mutate(work, { action: 'stash-drop', oid: state.stashes[0].oid, expectedHead: original }), /确认/);
    await workflows.mutate(work, { action: 'stash-drop', oid: state.stashes[0].oid, expectedHead: original, confirmed: true });
    await assert.rejects(() => workflows.mutate(work, { action: 'stash-apply', oid: state.stashes[0].oid, expectedHead: original }), /Stash/);
    run(tmp, ['clone', '--branch', 'main', remote, peer]); config(peer);
    fs.writeFileSync(path.join(peer, 'peer.txt'), 'remote commit\n'); run(peer, ['add', '-A']); run(peer, ['commit', '-m', 'remote']); run(peer, ['push']);
    await workflows.mutate(work, { action: 'pull', expectedHead: original }); assert(fs.existsSync(path.join(work, 'peer.txt')));
    const synced = await workflows.head(work);
    fs.writeFileSync(path.join(peer, 'peer.txt'), 'new remote\n'); run(peer, ['add', '-A']); run(peer, ['commit', '-m', 'other remote']); run(peer, ['push']);
    fs.writeFileSync(path.join(work, 'local.txt'), 'local\n'); run(work, ['add', '-A']); run(work, ['commit', '-m', 'diverge']);
    const divergent = await workflows.head(work);
    await assert.rejects(() => workflows.mutate(work, { action: 'pull', expectedHead: divergent }));
    assert.equal(await workflows.head(work), divergent, 'failed non-fast-forward pull preserves HEAD');
    assert.notEqual(synced, divergent);
    let release, acquired; const hold = new Promise(r => { release = r; }), entered = new Promise(r => { acquired = r; });
    const first = workflows.withLock(work, () => { acquired(); return hold; });
    await entered; await assert.rejects(() => workflows.withLock(work, async () => {}), /执行中/); release(); await first;
    console.log('[git-workflows] real branches, stale HEAD, stash content, fast-forward/divergent pull and repository locking passed');
  } finally { fs.rmSync(tmp, { recursive: true, force: true }); }
})().catch(e => { console.error(e); process.exitCode = 1; });
